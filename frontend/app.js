const renderWithTooltip = (label, termKey = null) => {
    const key = termKey || label;
    const def = FINANCE_TERMS[key];
    if (!def) return label;

    return `
        <span class="group relative inline-flex items-center gap-1 cursor-help">
            <span class="border-b border-dotted border-gray-500 group-hover:border-warren-accent transition-colors">${label}</span>
            <!-- Tooltip -->
            <div class="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-48 p-3 bg-gray-900 text-xs text-gray-300 rounded-lg shadow-[0_0_15px_rgba(0,0,0,0.5)] border border-gray-700 opacity-0 group-hover:opacity-100 transition-opacity pointer-events-none z-50 text-center leading-relaxed">
                ${def}
                <div class="absolute -bottom-1 left-1/2 -translate-x-1/2 w-2 h-2 bg-gray-900 border-r border-b border-gray-700 transform rotate-45"></div>
            </div>
        </span>
    `;
};

const renderMetricWithContext = (label, value, contextValue, unit = '') => {
    // Renders the label with definition tooltip (existing) AND the value with context tooltip
    const labelHtml = renderWithTooltip(label);

    if (contextValue === undefined || contextValue === null) return `<div class="flex justify-between items-center text-sm"><span class="text-gray-500">${labelHtml}</span><span class="text-gray-200 font-mono">${value}${unit}</span></div>`;

    let diff = parseFloat(value) - parseFloat(contextValue);
    let comparisonText = diff > 0 ? 'Higher than avg' : 'Lower than avg';
    let comparisonColor = diff > 0 ? 'text-warren-warning' : 'text-warren-success';
    // Logic: Usually lower P/E, Debt is better (Green), Higher is warning? Or simplistic. 
    // Let's keep color neutral-ish or context aware. 
    // For MVP, just show text.

    return `
    <div class="flex justify-between items-center text-sm">
        <span class="text-gray-500">${labelHtml}</span>
        
        <!-- Value with Context Tooltip Wrapper -->
        <span class="relative group cursor-help">
            <span class="text-gray-200 font-mono border-b border-dotted border-gray-600 group-hover:border-warren-accent transition-colors">${value}${unit}</span>
            
            <!-- Context Tooltip (Left aligned to value) -->
            <div class="absolute bottom-full right-0 mb-2 w-48 p-3 bg-gray-900 ring-1 ring-white/10 text-xs text-gray-300 rounded-lg shadow-2xl opacity-0 group-hover:opacity-100 transition-opacity pointer-events-none z-50 text-right">
                <div class="text-[10px] uppercase tracking-wider text-gray-500 font-bold mb-1">Industry Standard</div>
                <div class="flex justify-end items-baseline gap-2">
                    <span class="text-white font-mono font-bold text-sm">${contextValue}${unit}</span>
                    <span class="text-[10px] text-gray-400">Avg</span>
                </div>
                <div class="mt-1 pt-1 border-t border-gray-800 text-[10px] ${comparisonColor}">
                    ${comparisonText}
                </div>
                <!-- Arrow -->
                <div class="absolute -bottom-1 right-3 w-2 h-2 bg-gray-900 border-r border-b border-gray-700/50 transform rotate-45"></div>
            </div>
        </span>
    </div>
    `;
};

// 1. Load Market Status
async function loadMarketStatus() {
    try {
        const res = await fetch(`${API_BASE}/market-status`);
        const data = await res.json();

        // Update DOM
        document.getElementById('buffett-ratio').textContent = `${data.ratio_percent}%`;
        document.getElementById('market-cap-val').textContent = formatCurrency(data.market_cap);
        document.getElementById('gdp-val').textContent = formatCurrency(data.gdp);

        const badge = document.getElementById('buffett-status-badge');
        badge.textContent = data.rating;

        // Detailed style for gauge
        let colorClass = 'bg-gray-500';
        let badgeColor = 'white';

        if (data.rating.includes('Undervalued')) {
            colorClass = 'bg-warren-success';
            badge.className = `text-xl font-semibold px-4 py-1 rounded-full bg-green-500/20 text-green-400`;
        } else if (data.rating.includes('Fair')) {
            colorClass = 'bg-warren-warning'; // Yellowish/Gold
            badge.className = `text-xl font-semibold px-4 py-1 rounded-full bg-yellow-500/20 text-yellow-400`;
        } else {
            colorClass = 'bg-warren-danger';
            badge.className = `text-xl font-semibold px-4 py-1 rounded-full bg-red-500/20 text-red-400`;
        }

        // Calculate Gauge Width (Clamp between 0 and 100% relative to a max of ~200%)
        // Let's say max logical range is 200%.
        const maxScale = 200;
        const widthPct = Math.min((data.ratio_percent / maxScale) * 100, 100);

        const gaugeFill = document.getElementById('gauge-fill');
        gaugeFill.style.width = `${widthPct}%`;
        // Remove existing bg classes and add new one
        gaugeFill.className = `h-full transition-all duration-1000 ease-out w-0 ${colorClass}`;

    } catch (err) {
        console.error("Failed to load market status", err);
    }
}

